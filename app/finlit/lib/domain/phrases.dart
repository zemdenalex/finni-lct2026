/// Подстановка чисел в учебные тексты и согласование их с существительными.
///
/// Чистый Dart: этим пользуется и контент (`copy.json`), и разбор заданий,
/// то есть слой домена, куда Flutter не заходит.
///
/// 🔴 Отдельный модуль существует из-за режима «числа покрупнее». Пока все
/// числа были записаны в тексте словами («Зоопарк стоит 20»), умножение
/// экономики на пять делало условие задания враньём: на экране 100, в тексте
/// 20. Поэтому число в тексте задания больше не пишется — оно подставляется
/// из тех же параметров, которые считает движок. А как только число стало
/// подставляться, понадобилось согласование: «3 монетки», но «15 монеток».
abstract final class Phrases {
  /// «монетка / монетки / монеток» по числу.
  static String coinWord(int n) => _pick(n, 'монетка', 'монетки', 'монеток');

  /// «монету / монеты / монет» — винительный, слово «монеты» (правило
  /// Насти): «перевести 1 монету / 2 монеты / 30 монет» (банк, ТЗ экран 11).
  static String coinsAcc(int n) => _pick(n, 'монету', 'монеты', 'монет');

  /// «монета / монеты / монет» — именительный, слово «монеты» (правило
  /// Насти): «+1 монета», «+3 монеты», «+28 монет» (прибавка за опыт).
  static String coinsNom(int n) => _pick(n, 'монета', 'монеты', 'монет');

  /// Винительный: «заплатят 1 монетку / 2 монетки / 5 монеток» (BG-05).
  static String coinWordAcc(int n) => _pick(n, 'монетку', 'монетки', 'монеток');

  /// «раз / раза / раз» по числу: «1 раз», «2 раза», «5 раз».
  static String timesWord(int n) => _pick(n, 'раз', 'раза', 'раз');

  /// «неделя / недели / недель» по числу.
  static String weekWord(int n) => _pick(n, 'неделя', 'недели', 'недель');

  /// «день / дня / дней» по числу: «на 1 день», «на 3 дня», «на 5 дней».
  static String dayWord(int n) => _pick(n, 'день', 'дня', 'дней');

  /// «взять ещё 1 смену / 2 смены / 5 смен».
  static String shiftWord(int n) => _pick(n, 'смену', 'смены', 'смен');

  /// «1 процент / 2 процента / 5 процентов» — для озвучки (BG-05).
  static String percentWord(int n) =>
      _pick(n, 'процент', 'процента', 'процентов');

  /// Доля — монетами, без процентов (правило Насти Т6 А, 19.10; решение pm
  /// 19.10 вместо DEN-37 C): «Накоплено 640 из 1000». Так же читается вслух.
  static String partOf(int part, int whole) => '$part из $whole';

  static String _pick(int n, String one, String few, String many) {
    final int m10 = n.abs() % 10;
    final int m100 = n.abs() % 100;
    if (m100 >= 11 && m100 <= 14) return many;
    if (m10 == 1) return one;
    if (m10 >= 2 && m10 <= 4) return few;
    return many;
  }

  /// Заполняет шаблон значениями.
  ///
  /// Понимает три формы:
  /// * `{amount}` — только число;
  /// * `{amount:монетки}` — число со словом «монетка» в нужной форме;
  /// * `{amount:недели}` — то же со словом «неделя».
  ///
  /// Неизвестный ключ остаётся в тексте как есть: незаполненная подстановка
  /// должна быть видна тесту и человеку, а не молча превращаться в пустоту.
  static String fill(String template, Map<String, Object?> args) {
    String text = template;
    args.forEach((String key, Object? value) {
      if (value is int) {
        text = text.replaceAll('{$key:монетки}', '$value ${coinWord(value)}');
        text = text.replaceAll('{$key:недели}', '$value ${weekWord(value)}');
      }
      text = text.replaceAll('{$key}', '$value');
    });
    return text;
  }
}
