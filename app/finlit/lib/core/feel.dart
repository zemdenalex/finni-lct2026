import 'package:flutter/services.dart';
import 'package:flutter/widgets.dart';
import 'package:provider/provider.dart';

import '../app_state.dart';
import '../domain/models/profile.dart';

/// Короткий отклик на действие — щелчок и толчок вибромотора.
///
/// Видов ровно два, потому что различать больше нечем: платформа даёт всего
/// два системных звука, и второй из них тревожный — «не получилось». В игре
/// про монетки тревожный звук не нужен нигде.
enum Cue {
  /// Монетки пришли: карманные в начале недели, награда за задание.
  earn,

  /// Действие состоялось: покупка, взнос в копилку, перекладывание.
  done,
}

/// Единственное место, где спрашивают «можно ли сейчас звучать и двигаться».
///
/// 🔴 §3.6.7 требует, чтобы звуки и анимации отключались. Пока эта проверка
/// живёт внутри каждого экрана, следующий экран её просто не делает — и
/// переключатель в настройках снова становится украшением (именно так он и
/// прожил первые версии: флаги писались в профиль и не читались нигде).
/// Поэтому спрашивают здесь, и только здесь.
extension Feel on BuildContext {
  /// Можно ли издавать звук. Сюда же входит озвучка: для ребёнка «Звуки» —
  /// один тумблер «пусть игра меня не трогает», а не настройка подсистемы.
  bool get soundOn => _settings(this).soundOn;

  /// Можно ли двигать что-либо на экране.
  bool get motionOn {
    // 🔴 Системная просьба сильнее переключателя внутри игры. «Уменьшить
    // движение» в настройках телефона ставят не из вкуса, а потому что от
    // движения укачивает или начинается приступ. Флаг в профиле может быть
    // включён — движения всё равно не будет.
    if (MediaQuery.disableAnimationsOf(this)) return false;
    return _settings(this).animationsOn;
  }

  /// [motionOn] с подпиской на смену настроек — для того, кто движется
  /// долго и сам (тикер спрайта), а не только в момент построения.
  ///
  /// 🔴 Обычный [motionOn] читает профиль без подписки: его зовут и из
  /// обработчиков тапа, где подписка упала бы. Спрайт же запускает тикер
  /// один раз — без подписки «Анимации: выкл.» в настройках не доходили до
  /// Финни в комнате под ними, и он продолжал двигаться. Звать только из
  /// `build` / `didChangeDependencies`.
  bool get motionOnListening {
    try {
      Provider.of<AppState>(this);
    } on ProviderNotFoundException {
      // Без провайдера действуют настройки по умолчанию, см. [_settings].
    }
    return motionOn;
  }

  /// Длительность анимации: полная или нулевая.
  ///
  /// Нулевая длительность — это не «мгновенная анимация», а её отсутствие:
  /// implicit-виджеты и [AnimationController] с [Duration.zero] сразу
  /// оказываются в конечном состоянии. Явные же прокрутки нулевую
  /// длительность не принимают — там нужен [jumpTo], см. онбординг.
  Duration motion(Duration full) => motionOn ? full : Duration.zero;

  /// Короткий отклик на действие (§3.6.7 — гасится переключателем «Звуки»).
  ///
  /// Только `flutter/services`: внешняя аудио-библиотека — это ещё один
  /// плагин с нативной частью, лицензия на звуковой файл и вес пакета ради
  /// щелчка длиной в треть секунды. Системный щелчок звучит так же и уже
  /// настроен под громкость устройства.
  Future<void> cue(Cue kind) async {
    if (!soundOn) return;
    await SystemSound.play(SystemSoundType.click);
    // Вибрация — вторая половина отклика: она доходит до ребёнка, который
    // играет с выключённым звуком телефона. Гасится тем же переключателем.
    await switch (kind) {
      Cue.earn => HapticFeedback.mediumImpact(),
      Cue.done => HapticFeedback.selectionClick(),
    };
  }
}

/// Настройки текущего профиля — или значения по умолчанию.
///
/// Через try/catch: карточку последствия и отдельные виджеты показывают и до
/// `boot()`, и в виджет-тестах без провайдера над деревом. Отсутствие
/// состояния — это «настройки по умолчанию», а не повод падать.
GameSettings _settings(BuildContext context) {
  try {
    final AppState app = context.read<AppState>();
    return app.ready ? app.game.profile.settings : const GameSettings();
  } on Object {
    return const GameSettings();
  }
}
