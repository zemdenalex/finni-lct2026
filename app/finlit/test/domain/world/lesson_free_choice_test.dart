import 'package:finlit/domain/world/world_config.dart';
import 'package:flutter_test/flutter_test.dart';

import '../../support/world_harness.dart';

/// Регрессия 18.10 (регрессионный прогон): у урока после смены всегда есть
/// вариант, который не стоит монет. Иначе ребёнок без монет видит урок, где
/// все кнопки погашены (симулятор: «урок gardener: все варианты погашены» в
/// 115–133 из 500 прогонов случайной стратегии, урок «Лейка протекла»). Доли
/// в копилку и «Нужное» берутся из оплаты этой же смены, поэтому вариант без
/// траты доступен всегда. Уронит: новый урок, где каждый вариант что-то
/// покупает. Почему не ловят прежние: `lessons_test` запрещает «правильную
/// кнопку», но не проверяет, что хоть одна кнопка бесплатна.
void main() {
  test('у каждого урока есть вариант без траты монет', () {
    for (final WorldLesson l in contentDayConfig.lessons) {
      expect(l.choices.any((WorldLessonChoice c) => c.spend == 0), isTrue,
          reason: '${l.lessonId}: все варианты тратят монеты');
    }
  });
}
