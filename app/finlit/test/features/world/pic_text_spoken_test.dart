import 'package:finlit/features/world/pic_text.dart';
import 'package:flutter_test/flutter_test.dart';

/// Ловит (проход демо 16.10): TalkBack читает слово значка рядом с тем же
/// словом в тексте — «копилка Копилка: было…», «настроения Настроение».
/// Строки — настоящие строки итогов, истории и подсказок (список — grep
/// по lib и assets/content 16.10).
void main() {
  String spoken(String s) => PicText(s).spoken;

  test('слово значка не повторяет соседнее слово', () {
    for (final (String text, String said) in <(String, String)>[
      ('😊 Настроение: было 5 → стало 7', 'Настроение: было 5 → стало 7'),
      ('🐷 Копилка: было 0 → стало 0', 'Копилка: было 0 → стало 0'),
      ('🐷 В копилке: 0', 'В копилке: 0'),
      ('💰 — сколько монет стоит.', '— сколько монет стоит.'),
      ('Своих монет было 420 💰', 'Своих монет было 420'),
    ]) {
      expect(spoken(text), said, reason: text);
    }
  });

  // Слово дальше трёх слов — значок звучит: он подписывает всю строку.
  test('без слова рядом значок звучит словом', () {
    expect(spoken('🐷 Цель не выбрана · в копилке 40'),
        'копилка Цель не выбрана · в копилке 40');
    expect(spoken('−2 ⚡ · +5 😊'), '−2 сил · +5 настроения');
    expect(spoken('Счета недели: 460 💰'), 'Счета недели: 460 монет');
    expect(
        spoken('Из копилки уйдёт до 50 💰.'), 'Из копилки уйдёт до 50 монет.');
  });
}
